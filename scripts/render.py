"""Render digests/daily, digests/weekly, digests/sources and README.md from data/items.

Everything written here is regenerable; hand-written content lives in topics/ and notes/.
Usage: python scripts/render.py [--highlight-days N]
"""
from __future__ import annotations

import argparse
import datetime as dt
from collections import defaultdict

from common import DIGESTS, ROOT, STATUSES, load_items, load_yaml, today

STATUS_ICON = {"new": "🆕", "skimmed": "👀", "read": "✅", "noted": "📝"}
AUTOGEN = "<!-- AUTO-GENERATED by scripts/render.py — do not edit by hand -->\n"


def esc(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def rank(items):
    return sorted(items, key=lambda i: (not i.get("pinned"), -i.get("score", 0), i["date"]), reverse=False)


def topic_badges(it) -> str:
    return " ".join(f"`{t}`" for t in it.get("topics", [])) or "—"


def bullet(it, with_date=False) -> str:
    d = f"{it['date']} · " if with_date else ""
    star = "📌 " if it.get("pinned") else ""
    s = f"- {star}{STATUS_ICON.get(it.get('status'), '')} {d}**[{it['title']}]({it['url']})** · {topic_badges(it)} · score {it.get('score', 0):.2f}\n"
    if it.get("tldr"):
        s += f"  > {it['tldr']}\n"
    return s


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(AUTOGEN + text, encoding="utf-8")


def render_daily(items):
    by_day = defaultdict(list)
    for it in (i for i in items if not is_paper(i)):
        by_day[it["date"]].append(it)
    for day, rows in by_day.items():
        rel = [r for r in rows if r.get("topics")]
        other = [r for r in rows if not r.get("topics")]
        md = f"# Daily · {day}\n\n"
        if rel:
            md += "## On-topic\n\n" + "".join(bullet(r) for r in rank(rel)) + "\n"
        if other:
            md += "## Other\n\n" + "".join(f"- [{r['title']}]({r['url']}) · `{r['source']}`\n" for r in other)
        write(DIGESTS / "daily" / f"{day}.md", md)


def iso_week(d: str) -> str:
    y, w, _ = dt.date.fromisoformat(d).isocalendar()
    return f"{y}-W{w:02d}"


def render_weekly(items, topic_names):
    by_week = defaultdict(list)
    for it in (i for i in items if not is_paper(i)):
        by_week[iso_week(it["date"])].append(it)
    for wk, rows in by_week.items():
        md = f"# Weekly · {wk}\n\n{len(rows)} items, {sum(1 for r in rows if r.get('topics'))} on-topic.\n\n"
        for t in topic_names:
            hit = [r for r in rows if t in r.get("topics", [])[:1]]  # group by primary topic
            if hit:
                md += f"## {t}\n\n" + "".join(bullet(r, True) for r in rank(hit)) + "\n"
        other = [r for r in rows if not r.get("topics")]
        if other:
            md += "## Other\n\n" + "".join(f"- {r['date']} · [{r['title']}]({r['url']})\n" for r in sorted(other, key=lambda r: r["date"]))
        write(DIGESTS / "weekly" / f"{wk}.md", md)


def render_sources(items):
    by_src = defaultdict(list)
    for it in (i for i in items if not is_paper(i)):
        by_src[it["source"]].append(it)
    for src, rows in by_src.items():
        md = f"# Source tracker · `{src}`\n\n| Date | Title | Topics | Score | Status | Source tags |\n|---|---|---|---|---|---|\n"
        for r in sorted(rows, key=lambda r: r["date"], reverse=True):
            md += (f"| {r['date']} | [{esc(r['title'])}]({r['url']}) | {topic_badges(r)} | {r.get('score', 0):.2f} "
                   f"| {STATUS_ICON.get(r.get('status'), '')} {r.get('status', '')} | {', '.join(r.get('source_tags', []))} |\n")
        write(DIGESTS / "sources" / f"{src}.md", md)


LABS = [("openai", "OpenAI"), ("anthropic", "Anthropic"), ("google", "Google / DeepMind"), ("meta", "Meta"),
        ("xai", "xAI"), ("mistral", "Mistral"), ("aisi", "UK AISI"), ("hf-blog", "Hugging Face")]


def lab_of(it) -> str | None:
    tags = set(it.get("tags", []))
    return next((k for k, _ in LABS if k in tags), None)


def render_labs(items, days):
    """One page per window: every lab's posts, newest first, so nothing is lost to keyword filtering."""
    cutoff = (today() - dt.timedelta(days=days)).isoformat()
    md = f"# Lab timeline · last {days} days (since {cutoff})\n\n"
    md += "所有 lab 来源的全部条目（不经 topic 过滤）。🎯 = 命中关注 topic；类别来自源站。\n\n"
    for key, name in LABS:
        rows = sorted((i for i in items if lab_of(i) == key and i["date"] >= cutoff), key=lambda r: r["date"], reverse=True)
        if not rows:
            continue
        md += f"## {name} ({len(rows)})\n\n| Date | Title | Category | Topics |\n|---|---|---|---|\n"
        for r in rows:
            hit = "🎯 " if r.get("topics") else ""
            md += (f"| {r['date']} | {hit}[{esc(r['title'])}]({r['url']}) | {esc(', '.join(r.get('source_tags', [])[:2]))} "
                   f"| {topic_badges(r) if r.get('topics') else ''} |\n")
        md += "\n"
    write(DIGESTS / "labs.md", md)


PAPER_TOPICS = ["personal-agent", "code-computer-use", "office-agent", "professional-agent", "env-construction", "computer-use-agent", "browser-use-agent", "gui-agent-search", "agentic-rl", "agent-eval-safety", "agent-infra"]


def is_paper(it) -> bool:
    return "paper" in it.get("tags", [])


def paper_rank(it) -> float:
    """Reputation first, relevance second: rep in [0,1] plus half the topic score."""
    return it.get("rep", 0) + 0.5 * it.get("score", 0)


def paper_line(it) -> str:
    links = [f"[arXiv]({it['url']})"]
    if it.get("hf_url"):
        links.append(f"[HF]({it['hf_url']})")
    if it.get("github_repo"):
        links.append(f"[code]({it['github_repo']})")
    reasons = " · ".join(it.get("rep_reasons", [])) or "—"
    s = f"- {STATUS_ICON.get(it.get('status'), '')} **{esc(it['title'])}** · {it['date']} · rep {it.get('rep', 0):.2f} ({reasons}) · {' '.join(links)}\n"
    if it.get("tldr_source") == "manual":
        s += f"  > {it['tldr']}\n"
    return s


def render_papers(items, days, per_topic=25):
    cutoff = (today() - dt.timedelta(days=days)).isoformat()
    papers = [i for i in items if is_paper(i) and i["date"] >= cutoff and i.get("topics")]
    md = f"# Papers · last {days} days (since {cutoff})\n\n"
    md += ("来源：HF Daily Papers 与 arXiv（经 GitHub 镜像）。按口碑 rep 加相关度排序。rep 综合了 HF 点赞、机构、作者关注名单、"
           "顶会录用和开源代码，配置见 `config/reputation.yaml`。每篇只列在其首要 topic 下。\n\n")
    core = [i for i in papers if i["topics"][0] != "agent-infra" or len(i["topics"]) > 1]
    top = sorted((i for i in core if set(i["topics"]) - {"agent-infra"} and i.get("rep", 0) >= 0.4), key=paper_rank, reverse=True)[:15]
    md += "## 🔝 Must-read（核心 topic 且 rep ≥ 0.4）\n\n" + ("".join(paper_line(i) for i in top) or "_None._\n") + "\n"
    for t in PAPER_TOPICS:
        rows = [i for i in papers if (i["topics"][0] if i["topics"][0] != "agent-infra" or len(i["topics"]) == 1 else i["topics"][1]) == t]
        if not rows:
            continue
        rows.sort(key=paper_rank, reverse=True)
        md += f"## {t} ({len(rows)})\n\n" + "".join(paper_line(i) for i in rows[:per_topic])
        if len(rows) > per_topic:
            md += f"\n_…其余 {len(rows) - per_topic} 篇见 data/items（source = hf-daily-papers / arxiv-listing）_\n"
        md += "\n"
    write(DIGESTS / "papers.md", md)


STATUS_BADGE = {"空白": "🟥 空白", "上升": "🟧 上升", "拥挤": "🟦 拥挤", "观望": "⬜ 观望"}
CORE_TOPICS = {"personal-agent", "code-computer-use", "office-agent", "professional-agent", "env-construction", "computer-use-agent", "browser-use-agent", "gui-agent-search", "agentic-rl", "agent-eval-safety"}


def link(title, url) -> str:
    return f"[{esc(title)}]({url})"


def direction_hits(d, items, cutoff):
    """Recent items (papers + blogs) on a core topic whose title/abstract mentions any of the direction's keywords."""
    from classify import compile_kw
    pats = [compile_kw(k) for k in d.get("keywords", [])]
    def matches(i):  # a keyword in the title, or at least two distinct keywords in the abstract
        if any(p.search(i["title"]) for p in pats):
            return True
        return sum(1 for p in pats if p.search(i.get("excerpt", ""))) >= 2
    hits = [i for i in items if i["date"] >= cutoff and CORE_TOPICS & set(i.get("topics", [])) and matches(i)]
    return sorted(hits, key=lambda i: (paper_rank(i) if is_paper(i) else 0.5 + i.get("score", 0)), reverse=True)


def topic_heat(items, topic, days=14):
    """Share of papers on a topic, current window vs previous: shares cancel out changes in overall paper volume."""
    now = today()
    a = (now - dt.timedelta(days=days)).isoformat()
    b = (now - dt.timedelta(days=2 * days)).isoformat()
    cur_all = [i for i in items if is_paper(i) and i["date"] >= a]
    prev_all = [i for i in items if is_paper(i) and b <= i["date"] < a]
    cur = sum(1 for i in cur_all if topic in i.get("topics", []))
    prev = sum(1 for i in prev_all if topic in i.get("topics", []))
    cs, ps = cur / max(len(cur_all), 1), prev / max(len(prev_all), 1)
    arrow = "↑" if cs > ps * 1.2 else ("↓" if cs < ps * 0.8 else "→")
    return cur, cs, prev, ps, arrow


def review_title(path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return path.stem


def _readme_feeds(compass, items, by_id, cutoff, week, days, topic_names) -> str:
    md = ""
    # 1. directions: curated judgement + auto activity count
    dirs = compass.get("directions") or []
    if dirs:
        md += f"## 🧭 研究方向雷达\n\n状态是人工判断（[config/compass.yaml](https://github.com/demoleiwang/agent-frontier/blob/claude/inspiring-lovelace-umqw6v/config/compass.yaml)）；“近 {days} 天新工作”按关键词自动统计（核心 topic 的论文与 blog），用来看方向是否在变拥挤。\n\n"
        md += f"| 状态 | 方向 | 近 {days} 天新工作 | 下一步 |\n|---|---|---|---|\n"
        details = ""
        for d in dirs:
            hits = direction_hits(d, items, cutoff)
            top = f"：{link(hits[0]['title'][:48] + ('…' if len(hits[0]['title']) > 48 else ''), hits[0]['url'])}" if hits else ""
            ev0 = (d.get("evidence") or [{}])[0].get("url")
            name = f"**[{d['name']}]({ev0})**" if ev0 else f"**{d['name']}**"
            md += f"| {STATUS_BADGE.get(d.get('status'), d.get('status', ''))} | {name} | {len(hits)}{top} | {d.get('next', '')} |\n"
            ev = " · ".join(link(e["title"], e["url"]) for e in d.get("evidence", []))
            recent = "".join(f"  - {i['date']} · {link(i['title'], i['url'])}" + (f" · rep {i['rep']:.2f}" if is_paper(i) else "") + "\n" for i in hits[:3])
            details += (f"<details><summary><b>{d['name']}</b> — 为什么是现在</summary>\n\n{d.get('why', '').strip()}\n\n"
                        f"- 证据：{ev}\n" + (f"- 近期相关：\n{recent}" if recent else "") + "\n</details>\n")
        md += "\n" + details + "\n"

    # 2. pinned must-reads
    pins = compass.get("must_read") or []
    if pins:
        md += "## 📌 置顶必读\n\n"
        for p in pins:
            if p.get("id") and p["id"] in by_id:
                it = by_id[p["id"]]
                md += f"- {STATUS_ICON.get(it.get('status'), '')} {link(it['title'], it['url'])} — {p.get('why', '')}\n"
            elif p.get("url"):
                md += f"- 📄 {link(p['title'], p['url'])}" + (f" — {p['why']}" if p.get("why") else "") + "\n"
        md += "\n"

    # 3. signals
    sig = compass.get("signals") or []
    if sig:
        def srcs(x):
            refs = x.get("refs") or ([{"title": "来源", "url": x["ref"]}] if x.get("ref") else [])
            return "、".join(link(f["title"], f["url"]) for f in refs)
        md += "## 📡 关键信号\n\n" + "".join(f"- **{x['signal']}**：{x['detail']}（{srcs(x)}）\n" for x in sig) + "\n"

    # 4. this week's untriaged: new, core-topic, ranked
    new_papers = sorted((i for i in items if is_paper(i) and i["date"] >= week and i.get("status") == "new"
                         and CORE_TOPICS & set(i.get("topics", [])) and i.get("rep", 0) >= 0.3), key=paper_rank, reverse=True)[:8]
    new_blogs = rank([i for i in items if not is_paper(i) and i["date"] >= week and i.get("status") == "new"
                      and CORE_TOPICS & set(i.get("topics", []))])[:5]
    md += "## 🆕 本周待分拣\n\n近 7 天、核心 topic、尚未浏览的新工作。看完用 `python scripts/mark.py <id> skimmed --tldr \"…\"` 标记，标记后就不再出现在这里。\n\n"
    md += "**论文**（按口碑 + 相关度，rep ≥ 0.3）\n\n" + ("".join(paper_line(i) for i in new_papers) or "_无。_\n")
    md += "\n**Lab blog**\n\n" + ("".join(bullet(i, True) for i in new_blogs) or "_无。_\n") + "\n"

    # 5. topic heat
    md += (f"## 📊 Topic 热度\n\n论文数及其占同期论文总数的比例；趋势按占比比较（变化超过 ±20% 记 ↑↓），以抵消论文总量本身的波动。\n\n"
           f"| Topic | 近 {days} 天 | 前 {days} 天 | 趋势 | 人工页 |\n|---|---|---|---|---|\n")
    for t in topic_names:
        cur, cs, prev, ps, arrow = topic_heat(items, t, days)
        page = ROOT / "topics" / f"{t}.md"
        md += f"| `{t}` | {cur}（{cs:.1%}） | {prev}（{ps:.1%}） | {arrow} | {f'[topics/{t}.md](topics/{t}.md)' if page.exists() else '—'} |\n"
    return md


def render_readme(items, topic_names, days):
    """README = hand-curated research compass (config/compass.yaml) + auto signals that keep it current."""
    try:
        compass = load_yaml("compass.yaml") or {}
    except FileNotFoundError:
        compass = {}
    by_id = {i["id"]: i for i in items}
    cutoff = (today() - dt.timedelta(days=days)).isoformat()
    week = (today() - dt.timedelta(days=7)).isoformat()
    counts = {s: sum(1 for i in items if i.get("status") == s) for s in STATUSES}

    md = "# agent-frontier\n\n"
    md += compass.get("scope", "个人前沿追踪：browser / computer-use agent、agentic RL、agent 评测与安全。") + "\n\n"
    if compass.get("thesis"):
        md += f"> **当前判断**：{compass['thesis']}\n\n"
    md += (f"_罗盘更新于 {compass.get('updated', '—')}（人工）· 数据渲染于 {today().isoformat()}（自动）· "
           f"跟踪 {len(items)} 条 · 👀 {counts['skimmed']} 已浏览 · ✅ {counts['read']} 已读 · 📝 {counts['noted']} 有笔记_\n\n")
    dash = compass.get("dashboard") or {}
    compact = bool(dash.get("compact"))
    if dash:
        md += (f"**📊 交互网页（推荐）**：{link('打开罗盘', dash['artifact'])}（claude.ai，可从 GitHub 拉取每日最新数据）"
               + (f" · {link('静态版', dash['static'])}" if dash.get("static") else "")
               + "。方向雷达、本周新工作、主题热度、关键信号都在网页里，README 只保留主方向与模块。\n\n")
    if compact:
        md += ("[🎯 主方向](#-主方向) · " if compass.get("main_direction") else "") + "[🗂 报告与入口](#-报告与入口)\n\n"
    else:
        md += ("[🎯 主方向](#-主方向) · " if compass.get("main_direction") else "") + ("[🎯 下半年提案](#-下半年提案) · " if compass.get("proposals") else "") + "[🧭 研究方向](#-研究方向雷达) · [📌 必读](#-置顶必读) · [📡 关键信号](#-关键信号) · [🆕 本周待分拣](#-本周待分拣) · [📊 热度](#-topic-热度) · [🗂 报告与入口](#-报告与入口)\n\n"

    # 0. main direction, its modules, and when to revise it (curated)
    if compass.get("main_direction"):
        md += f"## 🎯 主方向\n\n{compass['main_direction']}\n\n"
        mods = compass.get("modules") or []
        if mods:
            md += (compass.get("modules_intro", "") + "\n\n" if compass.get("modules_intro") else "")
            md += "| 模块 | 做什么 | 状态 | 下一步 |\n|---|---|---|---|\n"
            for m in mods:
                name = f"**{link(m['id'] + ' ' + m['name'], m['url'])}**" if m.get("url") else f"**{m['id']} {m['name']}**"
                md += f"| {name} | {m.get('what', '')} | {m.get('status', '')} | {m.get('next', '')} |\n"
            md += "\n"
        watch = compass.get("watch") or []
        if watch:
            md += "**什么情况下修正主方向**\n\n| 信号 | 怎么改 |\n|---|---|\n"
            md += "".join(f"| {w['signal']} | {w['action']} |\n" for w in watch) + "\n"
        log = compass.get("direction_log") or []
        if log:
            md += "**方向修正记录**\n\n| 版本 | 日期 | 主方向 | 为什么改 |\n|---|---|---|---|\n"
            md += "".join(f"| {d['version']} | {d['date']} | {d['direction']} | {d['why']} |\n" for d in log) + "\n"
    props = compass.get("proposals") or []
    if props:
        md += "## 🎯 下半年提案\n\n" + (compass.get("proposals_intro", "") + "\n\n" if compass.get("proposals_intro") else "")
        md += "| 优先级 | 提案 | 一句话（附依据） | 投入 |\n|---|---|---|---|\n"
        for p in props:
            md += f"| {p.get('priority', '')} | **{link(p['name'], p['url']) if p.get('url') else p['name']}** | {p.get('pitch', '')} | {p.get('share', '')} |\n"
        md += "\n"

    if not compact:  # the dashboard shows these; README keeps them only in full mode
        md += _readme_feeds(compass, items, by_id, cutoff, week, days, topic_names)
    # 6. reports & entry points
    md += "\n## 🗂 报告与入口\n\n**深度报告（人工）**\n\n"
    for r in sorted((ROOT / "reviews").glob("*.md"), reverse=True)[:6]:
        md += f"- [{review_title(r)}](reviews/{r.name})\n"
    weeks = sorted({iso_week(i["date"]) for i in items if not is_paper(i)}, reverse=True)[:3]
    md += ("\n**自动摘要**\n\n"
           f"- [论文 · 近 30 天按口碑排序](digests/papers.md) · [各 lab 近 60 天全部条目](digests/labs.md)\n"
           "- 周报：" + ", ".join(f"[{w}](digests/weekly/{w}.md)" for w in weeks) + "\n"
           "- 来源：" + ", ".join(f"[{s}](digests/sources/{s}.md)" for s in sorted({i['source'] for i in items if not is_paper(i)})) + "\n")
    md += ("\n**维护**：每天 GitHub Actions 自动抓取、打分、渲染。每周人工约 20 分钟：清空“本周待分拣”，"
           "把值得留的写进 `topics/` 与 `notes/`，并更新 `config/compass.yaml` 中的方向状态、必读与信号。规划见 [PLAN.md](PLAN.md)。\n")
    (ROOT / "README.md").write_text(AUTOGEN.replace("do not edit by hand", "edit config/compass.yaml instead") + md, encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--highlight-days", type=int, default=14)
    args = ap.parse_args()
    cfg = load_yaml("topics.yaml")
    topic_names = [k for k in cfg if k != "authors"]
    items = list(load_items().values())
    render_daily(items)
    render_weekly(items, topic_names)
    render_sources(items)
    render_labs(items, 60)
    render_papers(items, 30)
    render_readme(items, topic_names, args.highlight_days)
    print(f"rendered {len(items)} items")


if __name__ == "__main__":
    main()
